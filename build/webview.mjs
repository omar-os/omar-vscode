// Bundle the diagram webview: the web app's DiagramCanvas, from the vendored
// omar checkout, with React and ELK, into one script and one stylesheet under
// media/webview/. The stylesheet is the diagram's own section of the web
// app's globals.css, cut out between two markers, plus its :root variables —
// the rest of that file styles the studio around it and pulls in Tailwind,
// which the webview has no use for. A moved marker fails the build loudly
// rather than shipping a diagram without its styles.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const vendor = resolve(root, "vendor/omar/web/app");
const out = resolve(root, "media/webview");
mkdirSync(out, { recursive: true });

const css = readFileSync(resolve(vendor, "globals.css"), "utf8");
const cut = (text, from, to, what) => {
  const start = text.indexOf(from);
  const end = text.indexOf(to, start + from.length);
  if (start < 0 || end < 0) throw new Error(`Could not find ${what} in globals.css; the markers have moved.`);
  return text.slice(start, end);
};
const variables = cut(css, ":root {", "}", "the :root variables") + "}\n";
const diagram = cut(css, "/* --- Lingua-Franca-inspired diagram grammar", ".inspector-panel {", "the diagram section");
writeFileSync(
  resolve(out, "diagram.css"),
  `/* Generated by build/webview.mjs from vendor/omar/web/app/globals.css. Do not edit. */\n${variables}* { box-sizing: border-box; }\n${diagram}`,
);

await build({
  entryPoints: [resolve(root, "webview/main.tsx")],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2020",
  jsx: "automatic",
  minify: true,
  sourcemap: false,
  outfile: resolve(out, "diagram.js"),
  define: { "process.env.NODE_ENV": '"production"' },
  logLevel: "warning",
});
console.log("webview bundled to media/webview/");
